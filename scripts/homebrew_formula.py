"""Generate the tap formula from verified, published macOS release archives."""
import argparse
import hashlib
from pathlib import Path

from release_version import release_version


def homebrew_formula(tag, directory):
    _, prerelease = release_version(tag)
    if prerelease:
        raise ValueError("Homebrew publishes stable releases only")

    checksums = {}
    for line in (directory / "SHA256SUMS").read_text().splitlines():
        digest, filename = line.split()
        if filename in checksums:
            raise ValueError(f"Duplicate checksum for {filename}")
        checksums[filename] = digest

    hashes = {}
    for arch in ("arm64", "amd64"):
        filename = f"kqt-darwin-{arch}.tar.gz"
        digest = hashlib.sha256((directory / filename).read_bytes()).hexdigest()
        if checksums.get(filename) != digest:
            raise ValueError(f"Missing or mismatched checksum for {filename}")
        hashes[arch] = digest

    return f'''# Generated by z0mbix/kqt scripts/homebrew_formula.py.
class Kqt < Formula
  desc "Keyboard-first Kubernetes browser with live resource tables and logs"
  homepage "https://github.com/z0mbix/kqt"
  version "{tag[1:]}"

  depends_on :macos

  on_macos do
    on_arm do
      url "https://github.com/z0mbix/kqt/releases/download/{tag}/kqt-darwin-arm64.tar.gz"
      sha256 "{hashes['arm64']}"
    end

    on_intel do
      url "https://github.com/z0mbix/kqt/releases/download/{tag}/kqt-darwin-amd64.tar.gz"
      sha256 "{hashes['amd64']}"
    end
  end

  def install
    bin.install "kqt"
    doc.install "README.md", "internal/tui/THEMES.md"
    (doc/"theme-licenses").install Dir["internal/tui/licenses/*.txt"]
  end

  test do
    assert_equal "kqt version v#{{version}}", shell_output("#{{bin}}/kqt --version").strip
    assert_match "Kubernetes", shell_output("#{{bin}}/kqt --help")
  end
end
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tag")
    parser.add_argument("release_directory", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    formula = homebrew_formula(args.tag, args.release_directory)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(formula)


if __name__ == "__main__":
    main()
